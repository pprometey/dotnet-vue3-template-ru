namespace DotnetVue3TemplateRu.Core.Application.UserContext;

/// <summary>
/// Идентичность текущего пользователя (scoped, на каждый HTTP-запрос).
/// Единственное, что видит приложение: оно зависит только от этого контракта и не знает,
/// каким провайдером выпущен токен и как назывались его claims (см. ADR 0023).
///
/// Прав здесь нет намеренно. Право обычно привязано к области - к записи, проекту, группе, -
/// а не к человеку целиком, и плоский список в токене такую модель не выражает. Поэтому
/// решение о доступе принимает обработчик предметного модуля по своим данным.
///
/// Профиля здесь тоже нет. Стандарт кладёт почту и имя в ID-токен и на эндпоинт
/// userinfo - то есть отдаёт их клиентскому приложению, а не API. Токен доступа,
/// который приезжает сюда, отвечает на вопрос "что предъявителю позволено",
/// и профильных claims в нём может не быть вовсе.
/// </summary>
public interface IUserContext
{
    bool IsAuthenticated { get; }

    /// <summary>Идентификатор пользователя у провайдера - значение claim "sub".</summary>
    string UserId { get; }
}
